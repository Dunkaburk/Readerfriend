import JSZip from 'jszip';

/**
 * Builds an EPUB in memory from a map of path → content. Binary entries take
 * Uint8Array. Deterministic — no timestamps, no ordering surprises.
 */
export async function makeEpub(files: Record<string, string | Uint8Array>): Promise<Uint8Array> {
  const zip = new JSZip();
  for (const [path, content] of Object.entries(files)) {
    zip.file(path, content);
  }
  return zip.generateAsync({ type: 'uint8array' });
}

