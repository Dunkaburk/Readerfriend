export function epub3Opf(opts: {
  title: string;
  author?: string;
  language?: string;
  manifest: string;
  spine: string;
}): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<package xmlns="http://www.idpf.org/2007/opf" version="3.0" unique-identifier="uid">
  <metadata xmlns:dc="http://purl.org/dc/elements/1.1/">
    <dc:identifier id="uid">urn:uuid:test</dc:identifier>
    <dc:title>${opts.title}</dc:title>
    ${opts.author ? `<dc:creator>${opts.author}</dc:creator>` : ''}
    <dc:language>${opts.language ?? 'en'}</dc:language>
    <meta property="dcterms:modified">2024-01-01T00:00:00Z</meta>
  </metadata>
  <manifest>${opts.manifest}</manifest>
  <spine>${opts.spine}</spine>
</package>`;
}

export function xhtmlDoc(title: string, body: string): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops" lang="en">
  <head><title>${title}</title></head>
  <body>${body}</body>
</html>`;
}

